def read_packet_registry(path=None):
    return json.loads(Path(path or REGISTRY_PATH).read_text(encoding='utf-8'))


def compute_ast_digest(node):
    description = describe_source_ast(node)
    return hashlib.sha256(description.encode('utf-8')).hexdigest()


def iter_packet_schemas(registry):
    """Enumerate ordinary protocols and separately declared wire variants."""
    for role, value in registry.get('roles', {}).items():
        for protocol, schema in value.get('protocols', {'': value}).items():
            yield role, protocol, schema
        for name, variant in value.get('wire_variants', {}).items():
            yield role, 'wire:' + name, variant['schema']


def _select_schema(role, packet, registry):
    value = registry.get('roles', {}).get(role)
    if value is None:
        return None
    for variant in value.get('wire_variants', {}).values():
        if variant['marker'] in packet:
            return variant['schema'] if packet[variant['marker']] == variant['equals'] else None
    if 'protocols' in value:
        protocol = packet.get('protocol', '')
        return value['protocols'].get(protocol)
    return value


def _check_declarations(schema, registry, path, errors, seen=()):
    if not isinstance(schema, dict):
        errors.append(INVALID_DECLARATION.format(path=path))
        return
    if 'opaque_json' in schema:
        declaration = schema['opaque_json']
        if (not isinstance(declaration, dict)
                or set(declaration) != {'limit_characters', 'provenance'}
                or not isinstance(declaration.get('provenance'), str)
                or '.' not in declaration.get('provenance', '')
                or not (type(declaration.get('limit_characters')) is int
                        and declaration['limit_characters'] > 0
                        or declaration.get('limit_characters') == 'request_limit')
                or set(schema).intersection({'$ref', 'members', 'items', 'values', 'keyed', 'grows'})):
            errors.append(INVALID_DECLARATION.format(path=path))
        return
    if '$ref' in schema:
        name = schema['$ref']
        if name not in registry.get('definitions', {}) or name in seen:
            errors.append(INVALID_DECLARATION.format(path=path))
        else:
            _check_declarations(registry['definitions'][name], registry, path, errors, seen + (name,))
        return
    if schema.get('grows'):
        if (schema.get('quantity') not in QUANTITIES or not schema.get('bound')
                or not schema.get('entry') or not schema.get('fixture')
                or schema['fixture'] not in registry.get('fixtures', {})):
            errors.append(INVALID_DECLARATION.format(path=path))
    for name, member in schema.get('members', {}).items():
        _check_declarations(member, registry, path + '.' + name, errors, seen)
    for key in ('items', 'values'):
        if key in schema:
            _check_declarations(schema[key], registry, path + '.*', errors, seen)


def validate_packet(role, packet, registry, *, request_limit_characters=None):
    """Return deterministic failures for undeclared members at their exact depth."""
    schema = _select_schema(role, packet, registry)
    if schema is None:
        template = UNKNOWN_ROLE if role not in registry.get('roles', {}) else UNKNOWN_VARIANT
        return [template.format(role=role, protocol=packet.get('protocol', ''))]
    errors = validate_open_members(registry)
    _check_declarations(schema, registry, role, errors)
    def visit(value, declaration, path):
        if '$ref' in declaration:
            declaration = registry.get('definitions', {}).get(declaration['$ref'], {})
        if 'opaque_json' in declaration:
            _check_opaque_value(value, declaration['opaque_json'], path, errors,
                                request_limit_characters)
            return
        if isinstance(value, dict):
            members = declaration.get('members', {})
            for name, item in value.items():
                child = members.get(name)
                if child is None and declaration.get('keyed'):
                    child = declaration.get('values')
                if child is None:
                    errors.append(UNDECLARED_MEMBER.format(path=path + '.' + str(name)))
                else:
                    visit(item, child, path + '.' + str(name))
        elif isinstance(value, list):
            for index, item in enumerate(value):
                visit(item, declaration.get('items', {}), path + '[' + str(index) + ']')
    visit(packet, schema, role)
    return sorted(set(errors))


def _check_opaque_value(value, declaration, path, errors, request_limit_characters):
    """Validate finite frozen JSON without treating its unknown keys as packet fields."""
    if not isinstance(declaration, dict):
        errors.append(OPAQUE_VALUE_INVALID.format(path=path))
        return
    limit = declaration.get('limit_characters')
    if limit == 'request_limit':
        limit = request_limit_characters
    if type(limit) is not int or limit <= 0:
        errors.append(OPAQUE_VALUE_INVALID.format(path=path))
        return
    try:
        text = json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False)
        # Refuse Python-only containers and non-string object keys, even when
        # JSONEncoder could coerce them into a different JSON value.
        valid = len(text) <= limit and json.loads(text) == value
    except (TypeError, ValueError, RecursionError):
        valid = False
    if not valid:
        errors.append(OPAQUE_VALUE_INVALID.format(path=path))


def _walk_declarations(schema, registry, path, seen=()):
    if '$ref' in schema:
        reference = schema['$ref']
        if reference in seen:
            return
        yield from _walk_declarations(registry['definitions'][reference], registry, path, seen + (reference,))
        return
    if schema.get('grows'):
        yield path, schema
    for name, child in schema.get('members', {}).items():
        yield from _walk_declarations(child, registry, path + (name,), seen)
    for key in ('items', 'values'):
        if key in schema:
            yield from _walk_declarations(schema[key], registry, path + ('*',), seen)


def validate_open_members(registry):
    """Keep the initial production allowance immutable while actual opens shrink."""
    if 'open_members' not in registry:
        return []
    baseline = registry['open_members']
    digest = hashlib.sha256(json.dumps(sorted(baseline), separators=(',', ':')).encode('utf-8')).hexdigest()
    if registry.get('certificates') and digest != OPEN_MEMBER_BASELINE_SHA256:
        return [OPEN_MEMBERS_CHANGED]
    actual = {role + '/' + protocol + ':' + '.'.join(path)
              for role, protocol, schema in iter_packet_schemas(registry)
              for path, member in _walk_declarations(schema, registry, ())
              if member.get('bound') == 'open'}
    return [] if actual <= set(baseline) else [OPEN_MEMBERS_CHANGED]


def read_quantity_allowance(registry, name):
    from research_harness.review_route_capacity import describe_route_capacity
    route = registry.get('quantity_routes', {}).get(name)
    if route is None:
        raise ValueError(QUANTITY_ROUTE_MISSING)
    records = registry.get('quantity_evidence', {}).get(name, {})
    return describe_route_capacity(route, records=records)['input_text_characters']['value']


def _read_quantity_scale(canonical, quantity, registry):
    dimension = canonical.get('dimension', 'characters' if quantity in ('texts', 'notes') else 'entries')
    if dimension == 'entries':
        return dimension, 10000
    allowance = read_quantity_allowance(registry, canonical.get('route'))
    if not allowance or canonical.get('route_limit', allowance) != allowance:
        raise ValueError(QUANTITY_ROUTE_CHANGED)
    return dimension, 30 * allowance


def generate_quantity_shapes(registry):
    """Generate one independent shape per growing declaration and fixture variant.

    Shapes carry a path and a 10,000-entry (or 30 route limits) value. The caller
    applies that value to the named fixture before invoking its packet builder.
    """
    open_errors = validate_open_members(registry)
    if open_errors:
        raise ValueError('; '.join(open_errors))
    for role, protocol, schema in sorted(iter_packet_schemas(registry), key=lambda row: row[:2]):
        errors = []
        _check_declarations(schema, registry, role, errors)
        if errors:
            raise ValueError('; '.join(errors))
        for path, member in _walk_declarations(schema, registry, ()):
            identity = role + '/' + protocol + ':' + '.'.join(path)
            contract = member.get('quantity_contract', registry.get('quantity_contracts', {}).get(identity, {}))
            canonical = contract.get('canonical')
            fixture_name = canonical.get('fixture', member['fixture']) if canonical else member['fixture']
            fixture = registry['fixtures'].get(fixture_name)
            if fixture is None or not fixture.get('builder'):
                raise ValueError(FIXTURE_MISSING.format(path='.'.join(path)))
            count = _read_quantity_scale(canonical, canonical.get('quantity', member['quantity']), registry)[1] if canonical else 10000
            sample = copy.deepcopy(member.get('sample', 'x'))
            if member.get('keyed'):
                value = {'item-' + str(index): copy.deepcopy(sample) for index in range(count)}
            elif 'items' in member:
                if canonical and canonical.get('dimension') == 'characters' and isinstance(sample, str):
                    value = [sample * count]
                else:
                    value = [copy.deepcopy(sample) for _ in range(count)]
            else:
                value = sample * count if isinstance(sample, str) else [copy.deepcopy(sample) for _ in range(count)]
            yield dict(role=role, protocol=protocol, path=path, fixture=fixture_name,
                       builder=fixture['builder'], coverage='canonical' if canonical else 'deferred' if contract.get('gap') else 'unassigned', quantity=member['quantity'],
                       entry=member['entry'], bound=member['bound'], count=count, value=value)


def _read_property_values(value, path):
    if not path:
        return [value]
    component = path[0]
    if component == '*':
        items = value.values() if isinstance(value, dict) else value if isinstance(value, list) else ()
        return [found for item in items for found in _read_property_values(item, path[1:])]
    if isinstance(value, dict) and component in value:
        return _read_property_values(value[component], path[1:])
    return []


def _measure_property_values(values, quantity, dimension):
    if dimension == 'characters':
        return sum(len(value) if isinstance(value, str) else len(json.dumps(value, sort_keys=True)) for value in values)
    return sum(len(value) if isinstance(value, (list, dict)) else 1 for value in values)


def inspect_quantity_factories(registry, matrix, factories):
    """Execute shipped properties; keep precise, merge-sensitive later-stage gaps.

    Factories scale upstream inputs. The declared production builder is traced,
    and a factory's returned value must equal a value captured at that call's
    return. A sparse/wire-only projection cannot provide canonical evidence.
    """
    import importlib
    from unittest.mock import patch
    errors = validate_open_members(registry)
    shipped = registry.get('shipped_quantity_properties', [])
    if registry.get('certificates'):
        shipped_digest = hashlib.sha256(json.dumps(sorted(shipped), separators=(',', ':')).encode('utf-8')).hexdigest()
        if shipped_digest != SHIPPED_QUANTITY_BASELINE_SHA256:
            errors.append(QUANTITY_COVERAGE_MISSING.format(path='shipped property baseline'))
    entries = {entry['id']: entry for entry in matrix['entries']}
    installed = set(matrix.get('installed_units', []))
    initial_open = set(registry.get('open_members', []))
    jobs = {}
    for role, protocol, schema in iter_packet_schemas(registry):
        declaration_errors = []
        _check_declarations(schema, registry, role, declaration_errors)
        if declaration_errors:
            errors.extend(declaration_errors)
            continue
        for path, member in _walk_declarations(schema, registry, ()):
            identity = role + '/' + protocol + ':' + '.'.join(path)
            if member['entry'] not in entries:
                errors.append(QUANTITY_COVERAGE_MISSING.format(path=identity))
                continue
            contract = member.get('quantity_contract', registry.get('quantity_contracts', {}).get(identity, {}))
            canonical = contract.get('canonical')
            gap = contract.get('gap')
            if isinstance(gap, str):
                definition = registry.get('quantity_gaps', {}).get(gap, {})
                gap = dict(definition, property=identity, declared_entry=contract.get('declared_entry'))
            if canonical:
                name = canonical.get('factory')
                definition = registry.get('quantity_factories', {}).get(name)
                component = {'research_harness.review_protocol._evidence': ('evidence',)}.get(definition.get('builder')) if definition else None
                expected_path = tuple(component or ()) + tuple(canonical.get('path', ()))
                fixture = registry.get('fixtures', {}).get(canonical.get('fixture', member['fixture']), {})
                if not definition or name not in factories or expected_path != path or fixture.get('builder') != definition.get('builder'):
                    errors.append(QUANTITY_FACTORY_MISSING.format(factory=name))
                    continue
                quantity = canonical.get('quantity', member['quantity'])
                try:
                    dimension, size = _read_quantity_scale(canonical, quantity, registry)
                except ValueError:
                    errors.append(QUANTITY_FACTORY_MISSING.format(factory=name))
                    continue
                scale_quantity = definition.get('scale_quantities', {}).get(quantity, quantity)
                jobs.setdefault((name, scale_quantity, size), []).append((identity, canonical, quantity, dimension))
            elif gap:
                entry = entries.get(gap.get('entry'))
                unit = gap.get('closing_unit')
                if (identity not in initial_open
                        or not entry or gap.get('declared_entry') != member['entry']
                        or unit not in entry['units']['construction'] or unit in installed
                        or gap.get('guard') not in ('capacity-guard-2', 'capacity-guard-3')
                        or gap.get('property') != identity
                        or gap.get('property_kind') not in ('frame_metadata', 'parts_frame_metadata', 'identifier_turn_lineage', 'reference_rows', 'session_metadata', 'historical_review_growth')):
                    errors.append(QUANTITY_COVERAGE_MISSING.format(path=identity))
            else:
                errors.append(QUANTITY_COVERAGE_MISSING.format(path=identity))
    scheduled = {identity for values in jobs.values() for identity, _, _, _ in values}
    if not set(shipped) <= scheduled:
        errors.extend(QUANTITY_COVERAGE_MISSING.format(path=identity) for identity in set(shipped) - scheduled)
    if errors:
        return sorted(set(errors))
    for (name, quantity, size), required in sorted(jobs.items()):
        definition = registry['quantity_factories'][name]
        module_name, _, function_name = definition['builder'].rpartition('.')
        module = importlib.import_module(module_name)
        original = getattr(module, function_name)
        observed = set()
        def describe(value):
            return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode('utf-8')).hexdigest()
        def invoke(*args, **kwargs):
            value = original(*args, **kwargs)
            observed.add(describe(value))
            return value
        with patch.object(module, function_name, side_effect=invoke):
            result = factories[name](quantity, size)
        results = result if definition.get('multiple_values') else [result]
        if not results or any(describe(value) not in observed for value in results):
            errors.append(QUANTITY_FACTORY_MISSING.format(factory=name))
            continue
        for identity, canonical, property_quantity, dimension in required:
            values = [value for emitted in results for value in _read_property_values(emitted, canonical['path'])]
            if not values or _measure_property_values(values, property_quantity, dimension) < size:
                errors.append(QUANTITY_NOT_SCALED.format(path=identity))
    return sorted(set(errors))


def build_quantity_shape_packet(shape, registry):
    """Build a minimal closed packet projection for one declared growing path.

    The projection retains its real role/protocol and collection addressing. It
    can be passed through the production wire builder without creating a store.
    """
    role = shape['role']
    selector = {'protocol': shape['protocol']}
    if shape['protocol'].startswith('wire:'):
        variant = registry['roles'][role]['wire_variants'][shape['protocol'][5:]]
        selector = {variant['marker']: variant['equals']}
    schema = _select_schema(role, selector, registry)
    while '$ref' in schema:
        schema = registry['definitions'][schema['$ref']]
    def build(path, declaration):
        if '$ref' in declaration:
            declaration = registry['definitions'][declaration['$ref']]
        if not path:
            return shape['value']
        component = path[0]
        if component == '*':
            if declaration.get('keyed'):
                return {'item-0': build(path[1:], declaration['values'])}
            return [build(path[1:], declaration.get('items', {}))]
        return {component: build(path[1:], declaration['members'][component])}
    packet = build(shape['path'], schema)
    if 'role' in schema.get('members', {}):
        packet.setdefault('role', role)
    elif 'kind' in schema.get('members', {}):
        packet.setdefault('kind', role)
    if shape['protocol'].startswith('wire:'):
        packet.setdefault(variant['marker'], variant['equals'])
    elif shape['protocol']:
        packet.setdefault('protocol', shape['protocol'])
    return packet


def _resolve_name(node):
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        parent = _resolve_name(node.value)
        return parent + '.' + node.attr if parent else None
    return None


def _read_root(node):
    while isinstance(node, (ast.Subscript, ast.Attribute)):
        node = node.value
    return node.id if isinstance(node, ast.Name) else None


def _read_strings(node, constants):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return {node.value}
    if isinstance(node, ast.Name):
        return constants.get(node.id)
    if isinstance(node, (ast.Tuple, ast.List, ast.Set)):
        result = set()
        for item in node.elts:
            values = _read_strings(item, constants)
            if values is None:
                return None
            result.update(values)
        return result
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _read_strings(node.left, constants), _read_strings(node.right, constants)
        if left is not None and right is not None:
            return {a + b for a in left for b in right}
    return None


def _collect_imports(tree, module):
    imports = {}
    package = module.rsplit('.', 1)[0] if '.' in module else ''
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                imports[alias.asname or alias.name] = alias.name
        elif isinstance(node, ast.ImportFrom):
            base = (package + '.' if node.level and package else '') + (node.module or '')
            for alias in node.names:
                imports[alias.asname or alias.name] = (base.rstrip('.') + '.' + alias.name).strip('.')
    return imports


def _collect_functions(tree):
    return {node.name: node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}


def _collect_member_names(registry):
    names = set(registry.get('source_members', []))
    def visit(value):
        if isinstance(value, dict):
            names.update(value.get('members', {}))
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)
    visit(registry.get('roles', {}))
    visit(registry.get('definitions', {}))
    return names


def _list_parameters(function):
    return [arg.arg for arg in function.args.posonlyargs + function.args.args + function.args.kwonlyargs]


def _collect_symbols(tree, module):
    """Name each function, class and lambda of a module at every depth, as the targets of call rows name them.

    A nested function or class gets two names: module.outer.inner and module.inner.
    """
    symbols = set()
    def collect(parent, prefix):
        for child in ast.iter_child_nodes(parent):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                symbols.add(prefix + '.' + child.name)
                symbols.add(module + '.' + child.name)
                collect(child, prefix + '.' + child.name)
            elif isinstance(child, ast.Lambda):
                symbols.add(module + '.<lambda>@' + compute_ast_digest(child))
            else:
                collect(child, prefix)
    collect(tree, module)
    return symbols


def _collect_callers(tree, module):
    """Name each function that a call row can name as its caller: the top-level functions and the methods of
    top-level classes."""
    callers = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            callers[module + '.' + node.name] = node
        elif isinstance(node, ast.ClassDef):
            callers.update((module + '.' + node.name + '.' + item.name, item) for item in node.body
                           if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)))
    return callers


def _collect_bound_names(tree):
    """Name every name that a module binds anywhere, so that a built-in of that name is not taken as the callee."""
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            names.add(node.id)
        elif isinstance(node, ast.arg):
            names.add(node.arg)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.alias):
            names.add((node.asname or node.name).partition('.')[0])
        elif isinstance(node, ast.ExceptHandler) and node.name:
            names.add(node.name)
    return names


def _find_caller_module(caller, modules):
    """Return the longest of modules that holds a dotted name such as a caller, or None.

    A caller is named module.function or module.Class.method. The targets of rows and the names that imports
    reach have the same form.
    """
    return max((module for module in modules if caller.startswith(module + '.')), key=len, default=None)


def _resolve_callee(module, node, imports, functions):
    """Return the dotted name that a callee expression reaches through the imports and the functions of its module.

    A name that another inspected module imports is followed to the module that defines it. A name whose first
    part the module neither imports nor defines as a top-level function is returned as written. The result is
    None for a callee that is not a plain or dotted name.
    """
    name = _resolve_name(node)
    if name is None:
        return None
    root, _, tail = name.partition('.')
    if root not in imports.get(module, {}):
        return module + '.' + name if root in functions.get(module, {}) else name
    name = imports[module][root] + ('.' + tail if tail else '')
    followed = set()
    owner = _find_caller_module(name, imports)
    while owner is not None and name not in followed:
        followed.add(name)
        head, _, rest = name[len(owner) + 1:].partition('.')
        if head not in imports[owner]:
            break
        name = imports[owner][head] + ('.' + rest if rest else '')
        owner = _find_caller_module(name, imports)
    return name


def _resolve_call_target(listed, caller, call):
    """Return the name that a call in caller reaches: a function nested in the caller, a method of the class of
    the caller through self, or the name that _resolve_callee gives."""
    written = _resolve_name(call.func)
    owner = caller.rpartition('.')[0]
    if written is not None and caller + '.' + written in listed['symbols']:
        return caller + '.' + written
    if (written is not None and written.startswith('self.') and owner in listed['symbols']
            and owner + written[4:] in listed['symbols']):
        return owner + written[4:]
    return _resolve_callee(listed['callers'][caller][0], call.func, listed['imports'], listed['functions'])


def _name_assignment_targets(node):
    """Name the targets of an assignment statement as mapping_sites rows name them: row['key'] is row.key."""
    names = set()
    for target in node.targets:
        if (isinstance(target, ast.Subscript) and isinstance(target.slice, ast.Constant)
                and isinstance(target.slice.value, str)):
            names.add(ast.unparse(target.value) + '.' + target.slice.value)
        else:
            names.add(ast.unparse(target))
    return names


def _index_sites(function):
    """Map the digest of each call and each assignment statement of a function to its nodes, in source order."""
    sites = {}
    for node in ast.walk(function):
        if isinstance(node, (ast.Call, ast.Assign)):
            sites.setdefault(compute_ast_digest(node), []).append(node)
    for nodes in sites.values():
        nodes.sort(key=lambda node: (node.lineno, node.col_offset))
    return sites


def _list_changed_sites(listed, collection, caller, callees, sites, declared):
    """List the undeclared sites of a caller that name one of callees, as {digest, line} in source order.

    A call names its written callee and the target that it reaches, or <dynamic>. For mapping_sites an assignment
    statement names its targets. One of these sites can be the call of a stale row in a changed form.
    """
    changed = []
    for digest, nodes in sites.items():
        if isinstance(nodes[0], ast.Call):
            names = {_resolve_name(nodes[0].func) or '<dynamic>', _resolve_call_target(listed, caller, nodes[0]) or '<dynamic>'}
        else:
            names = _name_assignment_targets(nodes[0]) if collection == 'mapping_sites' else set()
        if digest not in declared and names & callees:
            changed.append(dict(digest=digest, line=nodes[0].lineno))
    return sorted(changed, key=lambda site: (site['line'], site['digest']))


def list_packet_calls(function, builder_parameters=None):
    """List the calls in one function that pass a packet, in source order.

    The packet names of a function are its parameters with a name of PACKET_PARAMETER_NAMES, and the parameters
    with such a name of the functions and lambdas nested in it. In a builder that the registry declares
    (builder_parameters is not None), the parameters of its declaration and each name of PACKET_PARAMETER_NAMES
    that the builder uses are packet names too, because a builder holds the packet that it builds in a local.
    A plain local name that an assignment statement binds to an expression that holds a packet name is a packet
    name. A call passes a packet when one of its positional or keyword arguments holds a packet name: the packet
    itself, a part of it, or a value that the argument computes from it.
    """
    packet_names = set(builder_parameters or ())
    for node in ast.walk(function):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            packet_names.update(name for name in _list_parameters(node) if name in PACKET_PARAMETER_NAMES)
        elif builder_parameters is not None and isinstance(node, ast.Name) and node.id in PACKET_PARAMETER_NAMES:
            packet_names.add(node.id)
    if not packet_names:
        return []
    def holds_packet(value):
        return any(isinstance(node, ast.Name) and node.id in packet_names for node in ast.walk(value))
    assignments = [node for node in ast.walk(function)
                   if isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None]
    changed = True
    while changed:
        before = len(packet_names)
        for node in assignments:
            if holds_packet(node.value):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                packet_names.update(target.id for target in targets if isinstance(target, ast.Name))
        changed = len(packet_names) != before
    calls = [node for node in ast.walk(function) if isinstance(node, ast.Call) and any(
        holds_packet(argument) for argument in node.args + [keyword.value for keyword in node.keywords])]
    return sorted(calls, key=lambda node: (node.lineno, node.col_offset))


def _classify_callee(listed, module, written, reached, bound_names):
    """Return the classification that the source alone determines for a callee, or None when a reviewer gives it.

    A function, a class or a method of a listed module gets "listed module". A name that the module imports from
    outside the plugin, and a built-in whose name the module binds nowhere, get "standard library".
    """
    if reached in listed['symbols']:
        return 'listed module'
    if written is None:
        return None
    if written.partition('.')[0] in listed['imports'][module]:
        return 'standard library' if _find_caller_module(reached, listed['sources']) is None else None
    if written == reached and hasattr(builtins, written) and written not in bound_names:
        return 'standard library'
    return None


def _compare_rows_with_sites(registry, listed, declared):
    """List the differences of the declared rows from the source of their callers.

    The comparison checks four rules. A row names a call of its caller, or for mapping_sites a call or an
    assignment statement. A list holds a row at most as many times as the caller holds its node. The rows of one
    node in one list are equal. When the call of a callee_inventory row reaches a plugin function through the
    imports and the functions of its module, the row names that function. The fourth rule leaves out a call to a
    function nested in the caller and a call to a method through self, because the imports and the functions of
    the module do not give the function that such a call reaches.
    """
    differences, indexes = [], {}
    for collection in CALL_ROW_COLLECTIONS:
        groups = {}
        for row in registry.get(collection, []):
            groups.setdefault((row['caller'], row['ast_sha256']), []).append(row)
        for (caller, digest), rows in groups.items():
            if caller in listed['callers'] and caller not in indexes:
                indexes[caller] = _index_sites(listed['callers'][caller][1])
            sites = indexes.get(caller, {})
            nodes = [node for node in sites.get(digest, []) if collection == 'mapping_sites' or isinstance(node, ast.Call)]
            difference = dict(collection=collection, caller=caller, callee=rows[0]['callee'], digest=digest)
            if not nodes:
                undeclared = _list_changed_sites(listed, collection, caller, {row['callee'] for row in rows}, sites,
                                                 declared[caller])
                differences.append(dict(difference, kind='changed', undeclared=undeclared) if undeclared
                                   else dict(difference, kind='stale', held=0))
            elif any(row != rows[0] for row in rows):
                differences.append(dict(difference, kind='unequal'))
            elif len(rows) > len(nodes):
                differences.append(dict(difference, kind='stale', held=len(nodes)))
            elif collection == 'callee_inventory':
                module = listed['callers'][caller][0]
                reached = _resolve_callee(module, nodes[0].func, listed['imports'], listed['functions'])
                if (reached is not None and reached == _resolve_call_target(listed, caller, nodes[0])
                        and _find_caller_module(reached, listed['sources']) is not None
                        and (rows[0].get('classification') not in PLUGIN_CALLEE_CLASSIFICATIONS
                             or reached not in rows[0].get('targets', []))):
                    differences.append(dict(difference, kind='target', target=reached, line=nodes[0].lineno))
    return differences


def _compare_sites_with_rows(registry, listed, declared):
    """List each packet call in a function of a certified module that has no row, with the row that the source
    determines, or None for a callee that a reviewer classifies.

    A call that its caller holds several times is listed once, with its first line.
    """
    certificates, builders = registry.get('certificates', {}), registry.get('builders', {})
    differences, bound_names = [], {}
    for caller, (module, function) in listed['callers'].items():
        if module not in certificates:
            continue
        builder = builders.get(caller)
        seen = set(declared.get(caller, ()))
        for call in list_packet_calls(function, None if builder is None else builder.get('parameters', [])):
            digest = compute_ast_digest(call)
            if digest in seen:
                continue
            seen.add(digest)
            reached = _resolve_call_target(listed, caller, call)
            if module not in bound_names:
                bound_names[module] = _collect_bound_names(listed['trees'][module])
            classification = _classify_callee(listed, module, _resolve_name(call.func), reached, bound_names[module])
            row = None if classification is None else dict(
                ast_sha256=digest, callee=reached, caller=caller, classification=classification, targets=[reached])
            differences.append(dict(kind='missing', collection='callee_inventory', caller=caller,
                                    callee=reached or '<dynamic>', digest=digest, line=call.lineno, row=row))
    return differences


def describe_call_rows(sources, registry, parsed=None):
    """List every difference between the declared call rows and the source of their callers, in both directions.

    A row names one node of its caller by the digest of the node: a call, or for mapping_sites a call or an
    assignment statement. Each difference is a mapping with its kind, collection, caller, callee and digest:
    - stale: rows that name no node of their caller and are not changed (held is 0), or more copies of a row than
      the caller holds its node (held is the number of those nodes).
    - changed: rows that name no node of their caller while the caller holds undeclared calls to the same callee,
      or for mapping_sites undeclared assignment statements to the same target (undeclared: the digests and lines
      of those calls and statements). Those calls are not listed as missing, because the reviewer decides
      whether one of them is the declared call.
    - unequal: rows of one node in one list that differ.
    - target: a callee_inventory row whose call reaches a plugin function that the row does not name (target, line).
    - missing: a packet call without a row (line), with the row that the source determines, or None (row).
    parsed is the tuple of the trees, the imports, the functions and the symbols of the modules, each a mapping by
    module, from a caller that has them already.
    """
    modules = [module for module in registry.get('modules', []) if module in sources]
    if parsed is None:
        trees = {module: ast.parse(sources[module]) for module in modules}
        parsed = (trees, {module: _collect_imports(tree, module) for module, tree in trees.items()},
                  {module: _collect_functions(tree) for module, tree in trees.items()},
                  {module: _collect_symbols(tree, module) for module, tree in trees.items()})
    trees, imports, functions, symbols = ({module: table[module] for module in modules} for table in parsed)
    listed = dict(sources=sources, trees=trees, imports=imports, functions=functions,
                  symbols=set().union(*symbols.values()),
                  callers={caller: (module, function) for module in modules
                           for caller, function in _collect_callers(trees[module], module).items()})
    declared = {}
    for collection in CALL_ROW_COLLECTIONS:
        for row in registry.get(collection, []):
            declared.setdefault(row['caller'], set()).add(row['ast_sha256'])
    differences = _compare_rows_with_sites(registry, listed, declared)
    claimed = {(difference['caller'], site['digest'])
               for difference in differences if difference['kind'] == 'changed' for site in difference['undeclared']}
    return differences + [difference for difference in _compare_sites_with_rows(registry, listed, declared)
                          if (difference['caller'], difference['digest']) not in claimed]


def _collect_packet_call_digests(registry):
    """Collect, for each certified module, the digests of the call rows of its callers: its packet_call_digests."""
    digests = {module: set() for module in registry.get('certificates', {})}
    for collection in CALL_ROW_COLLECTIONS:
        for row in registry.get(collection, []):
            module = _find_caller_module(row['caller'], digests)
            if module is not None:
                digests[module].add(row['ast_sha256'])
    return digests


def inspect_packet_sources(sources, registry):
    """Inspect source text only; never import builders or read a record.

    Uncertified functions use conservative packet taint, propagated through local
    aliases, nested accesses, containers, returns and listed helper parameters.
    """
    errors = []
    for role, protocol, schema in iter_packet_schemas(registry):
        _check_declarations(schema, registry, role + '/' + protocol, errors)
    errors.extend(validate_open_members(registry))
    listed = set(registry.get('modules', []))
    readers = set(registry.get('readers', []))
    names = _collect_member_names(registry)
    nonmembers = set(registry.get('non_packet_names', {}))
    trees, functions, imports, constants = {}, {}, {}, {}
    reader_modules = set()
    for reader in readers:
        candidates = [module for module in sources if reader.startswith(module + '.')]
        reader_modules.add(max(candidates, key=len) if candidates else reader.rsplit('.', 1)[0])
    for module in listed | reader_modules:
        if module not in sources:
            errors.append(SOURCE_MISSING.format(module=module))
            continue
        tree = ast.parse(sources[module])
        trees[module] = tree
        functions[module] = _collect_functions(tree)
        imports[module] = _collect_imports(tree, module)
        values = {}
        for node in tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        value = _read_strings(node.value, values)
                        if value is not None:
                            values[target.id] = value
        constants[module] = values
    # AST certificates pin the complete module too: adding a function, an import,
    # a global alias or a side-effecting top-level statement cannot bypass review.
    certified_modules = registry.get('certificates', {})
    symbols = {module: _collect_symbols(tree, module) for module, tree in trees.items()}
    source_symbols = set().union(*symbols.values())
    for declaration in registry.get('callee_inventory', []):
        if declaration.get('classification') not in CALLEE_CLASSIFICATIONS or not declaration.get('targets'):
            errors.append(UNCLASSIFIED_CALL.format(site=declaration['caller'], callee=declaration['callee']))
        if declaration.get('classification') in PLUGIN_CALLEE_CLASSIFICATIONS:
            for target in declaration.get('targets', []):
                if target not in source_symbols:
                    errors.append(UNCLASSIFIED_CALL.format(site=declaration['caller'], callee=target))
    certified_sites = _collect_packet_call_digests(registry)
    for module, certificate in certified_modules.items():
        if module not in trees:
            continue
        if certified_sites[module] != set(certificate.get('packet_call_digests', [])):
            errors.append(CERTIFICATE_CHANGED.format(site=module))
        if compute_ast_digest(trees[module]) != certificate.get('ast_sha256'):
            errors.append(CERTIFICATE_CHANGED.format(site=module))
        for item in ast.walk(trees[module]):
            literal_keys = item.keys if isinstance(item, ast.Dict) else []
            for literal in literal_keys:
                if isinstance(literal, ast.Constant) and isinstance(literal.value, str) and literal.value not in names | nonmembers:
                    errors.append(UNDECLARED_WRITE.format(site=module, name=literal.value))
        for function, digest in certificate.get('functions', {}).items():
            node = functions[module].get(function)
            if node is None or compute_ast_digest(node) != digest:
                errors.append(CERTIFICATE_CHANGED.format(site=module + '.' + function))
    for difference in describe_call_rows(sources, registry, (trees, imports, functions, symbols)):
        undeclared = ', '.join('digest {} at line {}'.format(site['digest'][:12], site['line'])
                               for site in difference.get('undeclared', []))
        errors.append(CALL_ROW_MESSAGES[difference['kind']].format(
            site=difference['caller'], callee=difference['callee'], digest=difference['digest'][:12],
            collection=difference['collection'], line=difference.get('line'), target=difference.get('target'),
            undeclared=undeclared))
    # The walk below reads the callers of a certified function from the callee_inventory rows that target it.
    declared_callers = {}
    for declaration in registry.get('callee_inventory', []):
        for target in declaration.get('targets', []):
            declared_callers.setdefault(target, set()).add(declaration['caller'])
    pending = []
    for module, funcs in functions.items():
        if module in certified_modules:
            continue
        for name, node in funcs.items():
            parameters = _list_parameters(node)
            declared = registry.get('builders', {}).get(module + '.' + name)
            if declared is not None or module + '.' + name in readers:
                seeds = set(declared.get('parameters', []) if isinstance(declared, dict) else [])
                seeds.update(parameter for parameter in parameters if parameter in PACKET_PARAMETER_NAMES)
                pending.append((module, name, seeds))
    inspected = set()
    while pending:
        module, function, seeds = pending.pop()
        identity = module + '.' + function
        key = (identity, tuple(sorted(seeds)))
        if key in inspected:
            continue
        inspected.add(key)
        node = functions.get(module, {}).get(function)
        if node is None:
            errors.append(UNCLASSIFIED_CALL.format(site=identity, callee=identity))
            continue
        tainted = set(seeds)
        values = dict(constants.get(module, {}))
        globals_ = {name for item in ast.walk(node) if isinstance(item, ast.Global) for name in item.names}
        def contains_packet(value):
            return any(isinstance(item, ast.Name) and item.id in tainted for item in ast.walk(value))
        # A literal mapping or unresolved result can contain part of a packet.
        changed = True
        while changed:
            before = set(tainted)
            for item in ast.walk(node):
                if isinstance(item, (ast.Assign, ast.AnnAssign)):
                    value = item.value
                    if value is None:
                        continue
                    targets = item.targets if isinstance(item, ast.Assign) else [item.target]
                    packet_value = contains_packet(value) or isinstance(value, (ast.Dict, ast.DictComp))
                    if isinstance(value, ast.Call):
                        packet_value = packet_value or _resolve_callee(module, value.func, imports, functions) in registry.get('builders', {})
                    for target in targets:
                        if isinstance(target, ast.Name):
                            derived = _read_strings(value, values)
                            if derived is not None:
                                values[target.id] = derived
                            if packet_value:
                                tainted.add(target.id)
                elif isinstance(item, (ast.For, ast.comprehension)) and isinstance(item.target, ast.Name):
                    derived = _read_strings(item.iter, values)
                    if derived is not None:
                        values[item.target.id] = derived
                    if contains_packet(item.iter):
                        tainted.add(item.target.id)
            changed = tainted != before
        site = identity
        declarations = registry.get('computed_sites', {}).get(site, [])
        def check_write(key_node, target=None):
            if identity in readers and target is not None and _read_root(target) in tainted:
                errors.append(READER_WRITE.format(site=site))
                return
            if isinstance(key_node, ast.Constant) and isinstance(key_node.value, str):
                if key_node.value not in names | nonmembers:
                    errors.append(UNDECLARED_WRITE.format(site=site, name=key_node.value))
                return
            derived = _read_strings(key_node, values) if key_node is not None else None
            for declaration in declarations:
                form = declaration.get('form')
                if form == 'names' and derived is not None and set(declaration.get('names', [])) == derived and derived <= names:
                    return
                if (form == 'keyed' and declaration.get('member') in names
                        and target is not None and isinstance(target, ast.Subscript)
                        and isinstance(target.value, ast.Subscript)
                        and isinstance(target.value.slice, ast.Constant)
                        and target.value.slice.value == declaration['member']):
                    member = declaration.get('schema', {})
                    local_errors = []
                    _check_declarations(member, registry, declaration['member'], local_errors)
                    if member.get('grows') and member.get('values') and not local_errors:
                        return
                if form == 'no packet' and declaration.get('reason') and target is not None and _read_root(target) not in tainted:
                    return
            errors.append(COMPUTED_WRITE.format(site=site))
        for item in ast.walk(node):
            if isinstance(item, ast.Dict):
                for key_node in item.keys:
                    check_write(key_node)
            elif isinstance(item, ast.DictComp):
                check_write(item.key)
            elif isinstance(item, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
                targets = item.targets if isinstance(item, ast.Assign) else [item.target]
                for target in targets:
                    if isinstance(target, ast.Subscript):
                        check_write(target.slice, target)
                    if (isinstance(target, ast.Attribute) or isinstance(target, ast.Name) and target.id in globals_) and contains_packet(item.value):
                        errors.append(PACKET_ESCAPE.format(site=site))
            elif isinstance(item, ast.Call):
                callee = _resolve_callee(module, item.func, imports, functions)
                receiver = item.func.value if isinstance(item.func, ast.Attribute) else None
                method = item.func.attr if isinstance(item.func, ast.Attribute) else ''
                if receiver is not None and contains_packet(receiver) and method in ('update', 'setdefault', '__setitem__', 'pop', 'clear', 'popitem'):
                    if identity in readers:
                        errors.append(READER_WRITE.format(site=site))
                    if method == 'update':
                        for keyword in item.keywords:
                            check_write(ast.Constant(keyword.arg) if keyword.arg is not None else None, receiver)
                        for argument in item.args:
                            if isinstance(argument, ast.Dict):
                                continue
                            check_write(None, receiver)
                    elif method in ('setdefault', '__setitem__'):
                        check_write(item.args[0] if item.args else None, receiver)
                    continue
                if receiver is not None and contains_packet(receiver) and method in ('get', 'items', 'keys', 'values', 'copy'):
                    continue
                arguments = list(item.args) + [keyword.value for keyword in item.keywords]
                if not any(contains_packet(argument) for argument in arguments):
                    continue
                if callee in registry.get('stdlib_readers', []):
                    continue
                target_module, _, target_function = (callee or '').rpartition('.')
                if target_module in listed or callee in readers:
                    if target_module in certified_modules:
                        # A callee_inventory row of this caller declares the edge into the certified module.
                        if identity not in declared_callers.get(callee, ()):
                            errors.append(UNCLASSIFIED_CALL.format(site=site, callee=callee))
                        continue
                    target = functions.get(target_module, {}).get(target_function)
                    if target is not None:
                        parameters = [arg.arg for arg in target.args.posonlyargs + target.args.args]
                        passed = {parameters[index] for index, argument in enumerate(item.args)
                                  if index < len(parameters) and contains_packet(argument)}
                        passed.update(keyword.arg for keyword in item.keywords if keyword.arg and contains_packet(keyword.value))
                        pending.append((target_module, target_function, passed))
                        continue
                errors.append(UNCLASSIFIED_CALL.format(site=site, callee=callee or '<dynamic>'))
    # Discover reverse edges outside the list: a new consumer of a packet-returning
    # builder cannot evade the inventory merely by living in another module.
    for module, source in sources.items():
        if module in listed:
            continue
        tree = ast.parse(source)
        alias = _collect_imports(tree, module)
        for item in ast.walk(tree):
            if isinstance(item, ast.Call):
                called = _resolve_name(item.func) or ''
                root, _, tail = called.partition('.')
                called = alias.get(root, root) + ('.' + tail if tail else '')
                stores_assignment = any(isinstance(argument, ast.Constant) and argument.value == 'review_assignment'
                                        for argument in item.args) and isinstance(item.func, ast.Attribute) and item.func.attr in ('put', 'get')
                if called in registry.get('builders', {}) or stores_assignment or called.endswith(('.send_request', '.observe')):
                    errors.append(SOURCE_MISSING.format(module=module))
            elif isinstance(item, ast.Dict) and any(isinstance(key, ast.Constant) and key.value == 'packet' for key in item.keys):
                errors.append(SOURCE_MISSING.format(module=module))
    return sorted(set(errors))


def apply_call_rows(registry, differences):
    """Write the repairs that the source determines into the registry, and return the differences that stay.

    A stale row loses the copies beyond those that its caller holds, a missing row that the source determines
    joins callee_inventory, and packet_call_digests of every certificate is renewed from the rows. Every other
    difference stays for the reviewer: a changed row, unequal rows, a row that does not name the function of its
    call, and a missing row that the source does not determine. The digests of the modules and of the functions
    stay as the reviewer set them.
    """
    remaining = []
    for difference in differences:
        if difference['kind'] == 'stale':
            rows = registry[difference['collection']]
            positions = [index for index, row in enumerate(rows)
                         if (row['caller'], row['ast_sha256']) == (difference['caller'], difference['digest'])]
            for index in reversed(positions[difference['held']:]):
                del rows[index]
        elif difference['kind'] == 'missing' and difference['row'] is not None:
            registry['callee_inventory'].append(difference['row'])
        else:
            remaining.append(difference)
    digests = _collect_packet_call_digests(registry)
    for module, certificate in registry.get('certificates', {}).items():
        certificate['packet_call_digests'] = sorted(digests[module])
    return remaining


def format_packet_registry(registry):
    return json.dumps(registry, indent=2) + '\n'


def run_cli(argv=None):
    parser = argparse.ArgumentParser(
        prog='python3 -m ci.capacity_packet_inventory',
        description='Compare the declared call rows of the packet registry (the entries of callee_inventory, '
                    'mapping_sites and non_packet_sites) with the plugin sources. Print the differences as JSON, '
                    'and exit with status 1 when the printed list is not empty.')
    parser.add_argument('--root', type=Path, default=PLUGIN_ROOT,
                        help='the plugin root, which holds tests/fixtures/capacity_packet_schema.json and '
                             'research_harness (default: %(default)s)')
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--call-rows', action='store_true',
                        help='print each difference, and for a call without a row the row that the source determines')
    action.add_argument('--write-call-rows', action='store_true',
                        help='remove the rows whose call left the source and the copies of a row beyond the calls '
                             'that the source holds, add the rows that the source determines, renew '
                             'packet_call_digests, and print the differences that stay for a reviewer')
    args = parser.parse_args(argv)
    path = args.root / REGISTRY_PATH.relative_to(PLUGIN_ROOT)
    registry = read_packet_registry(path)
    sources = {'research_harness.' + source.stem: source.read_text(encoding='utf-8')
               for source in sorted((args.root / 'research_harness').glob('*.py'))}
    differences = describe_call_rows(sources, registry)
    if args.write_call_rows:
        differences = apply_call_rows(registry, differences)
        path.write_text(format_packet_registry(registry), encoding='utf-8')
    print(json.dumps(dict(differences=differences), indent=2, sort_keys=True))
    return 1 if differences else 0


if __name__ == '__main__':
    raise SystemExit(run_cli())
