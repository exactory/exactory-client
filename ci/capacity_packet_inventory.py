"""Closed packet schemas and a source-only guard for reviewer packet construction.

The legacy production declarations use AST certificates. A certificate pins a whole
function (including unreachable branches), its mapping writes and its calls. Changes
require a new review; certificates are never regenerated by the guard. Small/new
builders can instead use the ordinary, fail-closed data-flow checker below.

A call row is an entry of callee_inventory, mapping_sites or non_packet_sites. It declares one
call of its caller (for mapping_sites a call or an assignment statement) by the digest of that
call. The guard compares the call rows with the source of their callers in both directions:
each row names a call of its caller, and each call that passes a packet in a function of a
certified module has a row.
The command python3 -m ci.capacity_packet_inventory --write-call-rows repairs the differences
that the source determines and renews packet_call_digests from the rows. It changes no other
value of a certificate.
"""
