PARTS_COMMON = (
    'Review in parts. The role text above defines the scientific criteria, the evidence rules and the output of this '
    'review. The evidence of this review does not fit one input of this route, so the review runs as a series of '
    'turns under the protocol that review_parts.protocol names. This input is one turn of that series. Every turn is '
    'a fresh input: no earlier turn is replayed, and nothing reached you before this packet. What you need from the '
    'earlier turns is in this packet, as records that the harness built from the checked outputs of those turns. '
    'Checked means that the harness verified the shape, the handles and the statements of an output; it does not '
    'mean that the output is right.\n'
    '\n'
    'A collection is a list or a keyed object of the packet that the harness splits into its entries for this '
    'series. A unit is one such entry, called its item, together with the artifact contents that the packet attaches '
    'to it in evidence, called its bodies. Every unit has a handle: u1, u2 and so on. An item that appears at '
    'several places of the packet is one unit with several occurrences. The frame is the packet with every unit '
    'removed from its collection. Every turn carries the frame. A split collection is empty or partial in a turn '
    'that does not carry its units; that is not a part that the record lacks. review_parts.delivered_units lists the '
    'handles of the units whose content is in this packet, and review_parts.units gives one inventory row per such '
    'unit: handle; digest; item_characters, the characters of its item; characters, the characters of its item and '
    'its bodies together; occurrences, each a collection path with a key or an index; bodies, each with sha256, kind '
    "and characters; citations, the reference objects by which this review cites the unit's content; and "
    "carded_under where another unit's card covers it. A delivered unit is at its first occurrence in its "
    'collection, with its bodies in evidence. A text body, of kind utf-8 in its inventory row, that does not fit one '
    'read turn arrives in segments over consecutive read turns: an evidence entry with segment carries the '
    'characters of the whole body from start to end, where start and end are code point offsets in the whole body, '
    'start included and end excluded, and length is the length of the whole body. An item that does not fit one read '
    'turn arrives the same way, as segments of its canonical JSON text, in evidence entries with item true and the '
    "unit's handle in unit; the item is then not at its place in its collection. A body of another kind is delivered "
    'whole, never in segments. A unit whose content spans several turns is delivered again in each of them, with the '
    'segments of that turn.\n'
    '\n'
    'The series has four kinds of turn, in this order. Read turns deliver the units, a few at a time; you return one '
    'card per delivered unit. Combine turns deliver the cards; you return the combinations of units whose originals '
    'must be read together. Check turns deliver the originals of the combinations; you return one finding per '
    'combination. The final turn delivers the frame, every card, combination and finding, and the originals that '
    'fit; you return the review. A kind with no work is skipped. A unit that appears in the record while the series '
    'runs gets a read turn later, and a combine turn then reads its card against every card of the series. Only the '
    'final turn assesses the review. A read, combine or check turn judges nothing about its outcome.\n'
    '\n'
    'review_parts is the header of this turn. protocol and adapter name the protocol and the role adapter. '
    'series_assignment_id names the series; kind and turn name this turn. inventory_digest binds the list of the '
    "series' units. receipts holds one entry per earlier turn: turn, kind, assignment_id, attempt_id and "
    'output_digest. plan gives counts and estimates, for information. targets lists the targets of this review, the '
    "checks, items, objections or questions that the final review decides, each with id and label; a card's bearing, "
    "a read turn's unborne list and a combination's question name targets by id. output_allowance is a number of "
    'characters. In a read turn it bounds the JSON of the cards array; in a combine or check turn, the whole output; '
    'in a final turn, only the request object, which has 60,000 characters. An ordinary review in a final turn has '
    'no parts allowance; the validator of the role text and the output cap of the route bound it. '
    'statement_allowance.each is the number of characters one statement may have, and statement_allowance.turn the '
    'number that the statements of one turn may have together. review_parts_state carries the state that this kind '
    'of turn needs: a read turn, the earlier cards of the units it delivers again; a combine turn, the cards it '
    'reads; a check turn, its combinations and the cards of their units; the final turn, every card, combination and '
    "finding. Each carried record keeps the turn that produced it, and a carried card keeps its unit's inventory row "
    'and the count of its statements that were not verified. The harness builds the state only from the checked '
    'outputs of the earlier turns.\n'
    '\n'
    'A statement is a sentence or a passage copied character for character from the text that this turn delivered '
    'for its unit: for a body, a body segment or an item segment, the content of its evidence entry; for an item '
    "delivered whole, the item's text as the packet shows it. To match a statement, the harness changes each "
    'character of the statement and of that text to its Unicode compatibility form, called NFKC, and each run of '
    'white space to one space. It carries a statement into later turns only when it finds it, and a carried '
    'statement keeps where it was found in at: {"body":<sha256>,"start":s,"end":e} in a body, or '
    '{"item":true,"start":s,"end":e} in the item\'s canonical JSON text, with start and end as code point offsets in '
    'that whole text, start included and end excluded. A statement that the harness does not find is dropped, and '
    'the carried card records how many were dropped in unverified_statements. A dropped statement does not refuse '
    'your output. Where the role text has excerpt rules, statements take the place of excerpts in this series: '
    'return no excerpts field in a read, combine or check turn.\n'
    '\n'
    'In a read, combine or check turn, the turn text below gives your whole response; the response shape and the '
    'request rules of the role text do not apply to it. In a final turn, the response of the role text applies, with '
    'the changes that the final text states. Your answer is exactly one JSON object, and every top-level field of '
    'your answer is inside that object; in a final turn this includes excerpts, source_requests and reassessment '
    'where the role text allows them. Write the closing brace of the object only after its last field. Put nothing '
    'outside the object, except a RETRACTED correction where the role text allows one. The harness refuses an output '
    'over the allowance of its form, a read or check output with a missing or an extra card or finding, and an '
    'output that names a handle the inventory does not hold; two refusals exhaust the assignment.'
)

READ = (
    'This is a read turn. For every unit of review_parts.delivered_units, read all the content that this turn '
    'delivers for it: its item or its item segments, and its bodies or body segments. Interpret that content against '
    'the frame, which holds the record under review, and against the targets of review_parts.targets. Keep apart '
    'what the delivered content shows from what needs segments that this turn does not deliver. When a unit arrives '
    'again with further segments, review_parts_state.cards holds its earlier cards: write a new card from what this '
    'turn delivers, and repeat a statement of an earlier card only when this turn delivers its text again and the '
    'new card needs it. A unit that review_parts.units marks with carded_under gets no card of its own: the unit '
    'that carded_under names is in this turn as well, and its card covers both. In a problem review, a passage is '
    'carded under its reading.\n'
    '\n'
    'Return exactly '
    '{"kind":"read","turn":<review_parts.turn>,"cards":[...],"unborne":[{"target":id,"reason":text}]}. This object '
    'replaces the response shape of the role text for this turn. cards holds one card for every unit of '
    'review_parts.delivered_units without carded_under, and no other card, in any order. unborne lists exactly the '
    'targets of review_parts.targets that no card of this output bears on, each with a reason why none of the '
    'delivered units bears on it; a target is borne when a card has a bearing entry for it, of any relation. A card '
    'is '
    '{"unit":"<handle>","summary":text,"bearing":[{"target":id,"relation":r,"reason":text}],"statements":[{"text":tex'
    't,"why":text}],"depends_on":text,"questions":text}. The final reviewer reads the card in place of the unit, in '
    'a later fresh input, and decides from the frame, the cards and the verified statements. It cites the unit by '
    "the citations of the unit's inventory row, so the card carries no citation identity. Write each field so that "
    'this reviewer can rely on it.\n'
    '\n'
    'summary is nonblank. It states what the unit is, what it establishes and under which conditions, and what it '
    'leaves open. State only what the delivered content shows. Keep every condition that a conclusion kept in the '
    'card needs: its hypotheses, parameter ranges, stated inputs, scope and version. Name in questions the material '
    'that matters and that the card cannot keep.\n'
    '\n'
    'bearing has one entry per target that the unit bears on; a target that the unit does not bear on is not listed, '
    'and an empty list is valid. target is an id of review_parts.targets. relation is judged against the target as '
    'its label states it. supports: the unit is evidence for it. qualifies: the unit restricts it, by a condition, a '
    'scope, a version or a parameter range, or shows that it rests on a premise. contradicts: the unit is evidence '
    'against it. context: the unit is needed to understand the frame or other units but does not by itself support, '
    'qualify or contradict the target. reason names what in the unit gives the bearing. A card with a supports, '
    'qualifies or contradicts bearing has at least one statement; the harness refuses a card that has such a bearing '
    'and no statement.\n'
    '\n'
    'statements lists decisive passages of the unit in their original wording, chosen within statement_allowance and '
    'output_allowance: the definitions, the hypotheses and the conclusions of the results that bear on a target, the '
    'sentences that say that a question is open or settled, the stated inputs and the scope of a computation, the '
    'queries and the coverage of a search, and the sentences that a bearing rests on. text is copied character for '
    'character from the text that this turn delivered for this unit, or for a unit carded under it. Copy the '
    'decisive text itself, not the text around it. Split a passage longer than statement_allowance.each into '
    'consecutive statements, and say in why how they connect. Record in questions the decisive material that the '
    'allowances left out and the questions that this leaves open. why says in a few words what the statement '
    'decides. A statement has at most statement_allowance.each characters, and the statements of this output have at '
    'most statement_allowance.turn characters together.\n'
    '\n'
    "depends_on states what the unit's claims rest on outside the unit: other units, sources that the record does "
    'not deliver, the inputs of a computation. Name a unit by its handle when this packet gives the handle; '
    'otherwise name it by the identity or the citation that the delivered content gives. It is an empty string when '
    'there is nothing. questions states what the unit raises and does not settle, which unit might settle each '
    'question, named the same way, and what this card left out. It is an empty string when there is nothing.\n'
    '\n'
    'output_allowance counts the JSON of the cards array. Do not assess the review in this turn.'
)

